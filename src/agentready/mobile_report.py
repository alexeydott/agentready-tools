def _labels(lang: str) -> dict[str, str]:
    return _LABELS[normalize_language(lang)]


def _localized_check(check_id: str, title: str, category: str, lang: str) -> tuple[str, str, str]:
    active = normalize_language(lang)
    hint = _HINTS[active].get(check_id, f"This check covers “{title}”." if active == "en" else f"Проверка «{title}».")
    return title, category, hint


def _localized_category(category: str, lang: str) -> tuple[str, str]:
    active = normalize_language(lang)
    hint = _HINTS[active].get(category, f"Category: {category}" if active == "en" else f"Категория: {category}")
    return category, hint


def render_mobile_json(report: MobileReport, lang: str | None = None) -> str:
    return json.dumps(report.to_dict(), indent=2, ensure_ascii=False)


def render_mobile_console(report: MobileReport, lang: str | None = None) -> str:
    active = normalize_language(lang or report.language)
    labels = _labels(active)
    lines = [f"{labels['title']}: {', '.join(report.targets)}", f"{labels['score']}: {report.score}/100", ""]
    for page in report.pages:
        mode = labels["rendered"] if page.rendered else labels["static"]
        lines.append(f"{page.url} ({mode}): {page.score}/100")
        for check in page.checks:
            title, category, _ = _localized_check(check.id, check.title, check.category, active)
            lines.append(f"  [{labels.get(check.status, check.status)}] {title} ({category}) — {mobile_detail(check.details, active)}")
        lines.append("")
    if report.recommendations:
        lines.append(f"{labels['recommendations']}:")
        for item in report.recommendations:
            title, _, _ = _localized_check(item.check_id, item.title, "", active)
            lines.append(f"  {item.priority}. {title}: {mobile_summary(item.check_id, item.action, active)}")
    return "\n".join(lines).rstrip() + "\n"


def render_mobile_markdown(report: MobileReport, lang: str | None = None) -> str:
    labels = _labels(lang or report.language)
    lines = [
        f"# {labels['title']}", "", f"- {labels['generated_by']}: {datetime.now().astimezone().isoformat(timespec='seconds')}", f"- {labels['targets']}: `{', '.join(report.targets)}`",
        f"- {labels['score']}: **{report.score}/100**", "",
    ]
    for page in report.pages:
        mode = labels["rendered"] if page.rendered else labels["static"]
        lines.extend([f"## {page.url} ({mode})", "", f"- {labels['score']}: **{page.score}/100**", ""])
        lines.append(f"### {labels['checks']}")
        lines.append("")
        lines.append(f"| {labels['status']} | {labels['category']} | {labels['check']} | {labels['result']} |")
        lines.append("|---|---|---|---|")
        for check in page.checks:
            title, category, _ = _localized_check(check.id, check.title, check.category, lang or report.language)
            lines.append(f"| {labels.get(check.status, check.status)} | {category} | {title} (`{check.id}`) | {mobile_detail(check.details, lang or report.language).replace('|', '\\|')} |")
        lines.append("")
    lines.extend([f"## {labels['recommendations']}", ""])
    if report.recommendations:
        for item in report.recommendations:
            title, _, _ = _localized_check(item.check_id, item.title, "", lang or report.language)
            lines.append(f"{item.priority}. **{title}:** {mobile_summary(item.check_id, item.action, lang or report.language)}")
    else:
        lines.append(labels["no_items"])
    lines.extend(["", f"## {labels['remediation']}", ""])
    actionable = [check for page in report.pages for check in page.checks if check.remediation]
    if not actionable:
        lines.append(labels["no_items"])
    for check in actionable:
        remediation = check.remediation
        assert remediation is not None
        title, _, _ = _localized_check(check.id, check.title, check.category, lang or report.language)
        lines.extend([f"### {title}", "", mobile_summary(check.id, remediation.summary, lang or report.language), "", f"{labels['rerun']}: `{remediation.rerun_command}`"])
        if remediation.references:
            lines.append(labels["references"] + ": " + ", ".join(f"<{ref}>" for ref in remediation.references))
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def render_mobile_html(report: MobileReport, lang: str | None = None) -> str:
    active = normalize_language(lang or report.language)
    labels = _labels(active)
    generated = datetime.now().astimezone().isoformat(timespec="seconds")
    pages_html = ""
    for page in report.pages:
        mode = labels["rendered"] if page.rendered else labels["static"]
        rows = ""
        for check in page.checks:
            title, category, hint = _localized_check(check.id, check.title, check.category, active)
            rows += (
                f"<tr><td class='{html.escape(check.status)}'>{html.escape(labels.get(check.status, check.status))}</td>"
                f"<td>{html.escape(category)}</td><td class='check-cell'><span class='check-name'>{html.escape(title)}</span> "
                f"<span class='check-help' tabindex='0' role='img' aria-label='{html.escape(hint)}' data-tooltip='{html.escape(hint)}'>?</span>"
                f"<small><code>{html.escape(check.id)}</code></small></td>"
                f"<td>{html.escape(mobile_detail(check.details, active))}</td></tr>"
            )
        pages_html += f"<h2>{html.escape(page.url)} <small>({mode})</small></h2><p><strong>{labels['score']}: {page.score}/100</strong></p><div class='table-wrap'><table><caption>{html.escape(labels['checks'])}: {html.escape(page.url)}</caption><thead><tr><th scope='col'>{labels['status']}</th><th scope='col'>{labels['category']}</th><th scope='col'>{labels['check']}</th><th scope='col'>{labels['result']}</th></tr></thead><tbody>{rows}</tbody></table></div>"
    recommendations = "".join(
        f"<li><strong>{html.escape(_localized_check(item.check_id, item.title, '', active)[0])}</strong>: {html.escape(mobile_summary(item.check_id, item.action, active))}</li>"
        for item in report.recommendations
    ) or f"<p>{html.escape(labels['no_items'])}</p>"
    category_cards = []
    for item in report.categories:
        category, hint = _localized_category(item.category, active)
        score = "-" if item.score is None else f"{item.score}/100"
        category_cards.append(
            f"<div class='card'><strong>{html.escape(category)} "
            f"<span class='category-help check-help' tabindex='0' role='img' aria-label='{html.escape(hint)}' data-tooltip='{html.escape(hint)}'>?</span></strong>"
            f"<div class='score'>{html.escape(score)}</div><small>{item.passed}/{item.applicable}</small></div>"
        )
    remediation_items = []
    for page in report.pages:
        for check in page.checks:
            if check.remediation:
                refs = " ".join(f"<a href='{html.escape(ref)}'>{html.escape(ref)}</a>" for ref in check.remediation.references)
                remediation_items.append(
                    f"<h3>{html.escape(_localized_check(check.id, check.title, check.category, active)[0])}</h3><p>{html.escape(mobile_summary(check.id, check.remediation.summary, active))}</p>"
                    f"<p>{html.escape(labels['rerun'])}: <code>{html.escape(check.remediation.rerun_command)}</code></p><p>{refs}</p>"
                )
    remediation = "".join(remediation_items) or f"<p>{html.escape(labels['no_items'])}</p>"
    return f"""<!doctype html>
<html lang="{html.escape(report.language)}"><head><meta charset="utf-8">
<title>{html.escape(labels['title'])}</title>
<style>{BASE_REPORT_CSS}</style>
</head><body><a class="skip-link" href="#mobile-report-content">Skip to report content</a><main id="mobile-report-content"><h1>{html.escape(labels['title'])}</h1>
<p class="report-generated"><small>{html.escape(labels['generated_by'])}: {html.escape(generated)}</small></p>
<p>{html.escape(labels['targets'])}: <code>{html.escape(', '.join(report.targets))}</code></p>
<p><strong>{html.escape(labels['score'])}: {report.score}/100</strong></p>
<h2>{html.escape(labels['categories'])}</h2><div class="grid">{''.join(category_cards) or f"<p>{html.escape(labels['no_items'])}</p>"}</div>
{pages_html}
<details><summary><h3>{html.escape(labels['recommendations'])}</h3></summary><ol>{recommendations}</ol></details>
<details><summary><h3>{html.escape(labels['remediation'])}</h3></summary>{remediation}</details>
<script>window.addEventListener('beforeprint',()=>document.querySelectorAll('details').forEach(d=>d.open=true));</script>
</main></body></html>
"""


def render_mobile(report: MobileReport, fmt: str, lang: str | None = None) -> str:
    if fmt == "json":
        return render_mobile_json(report, lang)
    if fmt == "console":
        return render_mobile_console(report, lang)
    if fmt == "markdown":
        return render_mobile_markdown(report, lang)
    if fmt == "html":
        return render_mobile_html(report, lang)
    raise ValueError(f"unsupported mobile report format: {fmt}")
