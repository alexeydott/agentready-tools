def render_seo(report: SeoReport, fmt: str, lang: str | None = None) -> str:
    if fmt == "json":
        return render_seo_json(report, lang)
    if fmt == "jsonl":
        return render_seo_jsonl(report, lang)
    if fmt == "csv":
        return render_seo_csv(report, lang)
    if fmt == "console":
        return render_seo_console(report, lang)
    if fmt == "markdown":
        return render_seo_markdown(report, lang)
    if fmt == "html":
        return render_seo_html(report, lang)
    raise ValueError(f"unsupported SEO report format: {fmt}")
