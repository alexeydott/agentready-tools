def _labels(lang: str) -> dict[str, str]:
    return _LABELS[normalize_language(lang)]

def _localized_check(check_id: str, title: str, category: str, lang: str) -> tuple[str, str, str]:
    active = normalize_language(lang)
    metadata = _SEO_METADATA.get(check_id)
    if not metadata:
        return title, category, _SEO_HINTS[active].get(
            check_id,
            (
                f"This check covers “{title}”.\nIt helps improve reliable search discovery."
                if active == "en"
                else f"Проверка «{title}» помогает улучшить надёжное обнаружение страницы в поиске."
            ),
        )
    return (
        metadata["title"].get(active, title),
        metadata["category"].get(active, category),
        _SEO_HINTS[active].get(check_id, metadata["description"].get(active, "")),
    )


def _localized_category(category: str, lang: str) -> tuple[str, str]:
    active = normalize_language(lang)
    key = category.lower()
    return (
        _SEO_CATEGORY_NAMES[active].get(key, category),
        _SEO_CATEGORY_HINTS[active].get(
            key,
            (
                f"This category groups related SEO checks for {category}."
                if active == "en"
                else f"Категория «{category}» объединяет связанные SEO-проверки."
            ),
        ),
    )

def render_seo_json(report: SeoReport, lang: str | None = None) -> str:
    return json.dumps(report.to_dict(), indent=2, ensure_ascii=False)


def render_seo_console(report: SeoReport, lang: str | None = None) -> str:
    active = normalize_language(lang or report.language)
    labels = _labels(active)
    lines = [f"{labels['title']}: {report.target}", f"{labels['score']}: {report.score}/100", ""]
    lines.append(f"{labels['checks']}:")
    for check in report.checks:
        title, category, _ = _localized_check(check.id, check.title, check.category, active)
        lines.append(f"[{labels.get(check.status, check.status)}] {title} ({category}) — {seo_detail(check.details, active)}")
        for item in check.evidence:
            if item.url:
                lines.append(f"  {labels['evidence']} URL: {item.url}")
            if item.metrics:
                lines.append(f"  {labels['evidence']} metrics: {json.dumps(item.metrics, ensure_ascii=False, separators=(',', ':'))}")
    lines.extend(["", f"{labels['categories']}:"])
    lines.extend(
        f"  {_localized_category(item.category, active)[0]}: {item.score if item.score is not None else '-'}"
        for item in report.categories
    )
    if report.recommendations:
        lines.extend(["", f"{labels['recommendations']}:"])
        lines.extend(
            f"  {item.priority}. {_localized_check(item.check_id, item.title, '', active)[0]}: {seo_summary(item.check_id, item.action, active)}"
            for item in report.recommendations
        )
    return "\n".join(lines) + "\n"


def _metric_html(value: object, depth: int = 0) -> str:
    if depth > 3:
        return f"<code>{html.escape(str(value))}</code>"
    if isinstance(value, dict):
        items = "".join(
            f"<li><strong>{html.escape(str(key))}:</strong> {_metric_html(item, depth + 1)}</li>"
            for key, item in value.items()
        )
        return f"<ul>{items}</ul>"
    if isinstance(value, (list, tuple)):
        items = "".join(f"<li>{_metric_html(item, depth + 1)}</li>" for item in value[:100])
        return f"<ul>{items}</ul>"
    return f"<code>{html.escape(str(value))}</code>"


def _additional_details_html(check: object, labels: dict[str, str]) -> str:
    status = getattr(check, "status", "")
    if status not in {"fail", "warn", "error"}:
        logger.debug("[FIX] Suppressed additional SEO evidence for status=%s", status)
        return ""
    evidence = getattr(check, "evidence", [])
    if not evidence:
        return ""
    items: list[str] = []
    for item in evidence:
        fields = [
            (labels["evidence"], getattr(item, "action", "")),
            ("URL", getattr(item, "url", "")),
            ("HTTP", getattr(item, "status_code", "")),
            ("Finding", getattr(item, "finding", "")),
        ]
        content = "".join(
            f"<p><strong>{html.escape(str(label))}:</strong> {html.escape(str(value))}</p>"
            for label, value in fields
            if value not in ("", None)
        )
        metrics = getattr(item, "metrics", {}) or {}
        if metrics:
            content += "".join(
                f"<div><strong>{html.escape(str(key))}:</strong> {_metric_html(value)}</div>"
                for key, value in metrics.items()
            )
        if content:
            items.append(f"<li>{content}</li>")
    if not items:
        return ""
    return (
        f"<details class='additional-details'><summary>{html.escape(labels['additional'])}</summary>"
        f"<ul>{''.join(items)}</ul></details>"
    )


def _affected_pages_html(check: object, labels: dict[str, str]) -> str:
    if getattr(check, "id", "") != "insecure-links-pages" or getattr(check, "status", "") not in {"fail", "warn", "error"}:
        return ""
    pages = [
        item for item in getattr(check, "evidence", [])
        if getattr(item, "url", None)
    ]
    if not pages:
        return ""
    items = "".join(
        f"<li><a href='{html.escape(str(item.url), quote=True)}'>{html.escape(str(item.url))}</a>"
        + (
            f" — {html.escape(str(item.finding))}"
            if getattr(item, "finding", None)
            else ""
        )
        + "</li>"
        for item in pages[:50]
    )
    return (
        f"<div class='affected-pages'><strong>{html.escape(labels['affected_pages'])}:</strong>"
        f"<ul>{items}</ul></div>"
    )


def render_seo_markdown(report: SeoReport, lang: str | None = None) -> str:
    labels = _labels(lang or report.language)
    lines = [
        f"# {labels['title']}", "", f"- {labels['generated_by']}: {datetime.now().astimezone().isoformat(timespec='seconds')}", f"- {labels['target']}: `{report.target}`",
        f"- {labels['score']}: **{report.score}/100**", "",
        f"## {labels['checks']}", "",
        f"| {labels['status']} | {labels['category']} | {labels['check']} | {labels['result']} |",
        "|---|---|---|---|",
    ]
    for check in report.checks:
        title, category, _ = _localized_check(check.id, check.title, check.category, lang or report.language)
        lines.append(f"| {labels.get(check.status, check.status)} | {category} | {title} (`{check.id}`) | {seo_detail(check.details, lang or report.language).replace('|', '\\|')} |")
    evidence_items = [
        (check.id, item)
        for check in report.checks
        for item in check.evidence
        if item.url or item.metrics or item.finding
    ]
    if evidence_items:
        lines.extend(["", f"## {labels['evidence']}", ""])
        for check_id, item in evidence_items:
            parts = [f"**{check_id}**"]
            if item.url:
                parts.append(f"URL: `{item.url}`")
            if item.finding:
                parts.append(item.finding)
            if item.metrics:
                parts.append(f"metrics: `{json.dumps(item.metrics, ensure_ascii=False, separators=(',', ':'))}`")
            lines.append("- " + " — ".join(parts))
    lines.extend(["", f"## {labels['categories']}", ""])
    lines.extend(
        f"- **{_localized_category(item.category, lang or report.language)[0]}:** {item.score}/100 ({item.passed}/{item.applicable})"
        for item in report.categories
    )
    lines.extend(["", f"## {labels['recommendations']}", ""])
    if report.recommendations:
        lines.extend(f"{item.priority}. **{_localized_check(item.check_id, item.title, '', lang or report.language)[0]}:** {seo_summary(item.check_id, item.action, lang or report.language)}" for item in report.recommendations)
    else:
        lines.append(labels["no_items"])
    lines.extend(["", f"## {labels['remediation']}", ""])
    actionable = [item for item in report.checks if item.remediation]
    if not actionable:
        lines.append(labels["no_items"])
    for item in actionable:
        remediation = item.remediation
        assert remediation is not None
        title, _, _ = _localized_check(item.id, item.title, item.category, lang or report.language)
        lines.extend([f"### {title}", "", seo_summary(item.id, remediation.summary, lang or report.language), "", f"{labels['rerun']}: `{remediation.rerun_command}`"])
        if remediation.references:
            lines.append(labels["references"] + ": " + ", ".join(f"<{ref}>" for ref in remediation.references))
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def render_seo_html(report: SeoReport, lang: str | None = None) -> str:
    active = normalize_language(lang or report.language)
    labels = _labels(active)
    generated = datetime.now().astimezone().isoformat(timespec="seconds")
    rows = ""
    for item in report.checks:
        title, category, hint = _localized_check(item.id, item.title, item.category, active)
        rows += (
            f"<tr><td class='{html.escape(item.status)}'>{html.escape(labels.get(item.status, item.status))}</td>"
            f"<td>{html.escape(category)}</td><td class='check-cell'><span class='check-name'>{html.escape(title)}</span> "
            f"<span class='check-help' tabindex='0' role='img' aria-label='{html.escape(hint)}' data-tooltip='{html.escape(hint)}'>?</span>"
            f"<small><code>{html.escape(item.id)}</code></small></td>"
            f"<td>{html.escape(seo_detail(item.details, active))}{_affected_pages_html(item, labels)}"
            f"{_additional_details_html(item, labels)}</td></tr>"
        )
    recommendations = "".join(
        f"<li><strong>{html.escape(_localized_check(item.check_id, item.title, '', active)[0])}</strong>: {html.escape(seo_summary(item.check_id, item.action, active))}</li>"
        for item in report.recommendations
    ) or f"<p>{html.escape(labels['no_items'])}</p>"
    category_cards = []
    for item in report.categories:
        category, hint = _localized_category(item.category, active)
        score = "-" if item.score is None else f"{item.score}/100"
        category_cards.append(
            f"<div class='card'><strong>{html.escape(category)} "
            f"<span class='category-help check-help' tabindex='0' role='img' aria-label='{html.escape(hint)}' data-tooltip='{html.escape(hint)}'>?</span></strong>"
            f"<div class='score'>{html.escape(score)}</div><small>{item.passed}/{item.applicable}</small></div>"
        )
    remediation_items = []
    for item in report.checks:
        if item.remediation:
            refs = " ".join(f"<a href='{html.escape(ref)}'>{html.escape(ref)}</a>" for ref in item.remediation.references)
            remediation_items.append(
                f"<h3>{html.escape(_localized_check(item.id, item.title, item.category, active)[0])}</h3><p>{html.escape(seo_summary(item.id, item.remediation.summary, active))}</p>"
                f"<p>{html.escape(labels['rerun'])}: <code>{html.escape(item.remediation.rerun_command)}</code></p><p>{refs}</p>"
            )
    remediation = "".join(remediation_items) or f"<p>{html.escape(labels['no_items'])}</p>"
    return f"""<!doctype html>
<html lang="{html.escape(report.language)}"><head><meta charset="utf-8">
<title>{html.escape(labels['title'])}</title>
<style>{BASE_REPORT_CSS}.affected-pages{{margin:.5rem 0;font-size:.92rem}}.affected-pages ul{{margin:.4rem 0;padding-left:1.2rem}}.additional-details{{margin:.5rem 0;font-size:.92rem}}.additional-details ul{{margin:.4rem 0;padding-left:1.2rem}}.additional-details p{{margin:.25rem 0}}</style>
</head><body><h1>{html.escape(labels['title'])}</h1>
<p class="report-generated"><small>{html.escape(labels['generated_by'])}: {html.escape(generated)}</small></p>
<p>{html.escape(labels['target'])}: <code>{html.escape(report.target)}</code></p>
<p><strong>{html.escape(labels['score'])}: {report.score}/100</strong></p>
<h2>{html.escape(labels['categories'])}</h2><div class="grid">{''.join(category_cards) or f"<p>{html.escape(labels['no_items'])}</p>"}</div>
<h2>{html.escape(labels['checks'])}</h2><table><thead><tr><th>{html.escape(labels['status'])}</th><th>{html.escape(labels['category'])}</th><th>{html.escape(labels['check'])}</th><th>{html.escape(labels['result'])}</th></tr></thead><tbody>{rows}</tbody></table>
<details><summary>{html.escape(labels['recommendations'])}</summary><ol>{recommendations}</ol></details>
<details><summary>{html.escape(labels['remediation'])}</summary>{remediation}</details>
<script>window.addEventListener('beforeprint',()=>document.querySelectorAll('details').forEach(d=>d.open=true));</script>
</body></html>
"""


def render_seo(report: SeoReport, fmt: str, lang: str | None = None) -> str:
    if fmt == "json":
        return render_seo_json(report, lang)
    if fmt == "console":
        return render_seo_console(report, lang)
    if fmt == "markdown":
        return render_seo_markdown(report, lang)
    if fmt == "html":
        return render_seo_html(report, lang)
    raise ValueError(f"unsupported SEO report format: {fmt}")
