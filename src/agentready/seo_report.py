def _labels(lang: str) -> dict[str, str]:
    return _LABELS[normalize_language(lang)]

def _localized_check(check_id: str, title: str, category: str, lang: str) -> tuple[str, str, str]:
    active = normalize_language(lang)
    metadata = _SEO_METADATA.get(check_id)
    if not metadata:
        if active == "ru" and check_id in _SITE_CHECK_TITLES_RU:
            return _SITE_CHECK_TITLES_RU[check_id], _localized_category(category, active)[0], _SEO_HINTS[active].get(check_id, "Проверяет соответствующий сигнал SEO на уровне сайта.")
        return title, category, _SEO_HINTS[active].get(
            check_id,
            (
                f"This check covers “{title}”.\nIt helps improve reliable search discovery."
                if active == "en"
                else f"Проверка «{title}» помогает улучшить надёжное обнаружение страницы в поиске."
            ),
        )
    return (
        metadata["title"].get(active, title),
        metadata["category"].get(active, category),
        _SEO_HINTS[active].get(check_id, metadata["description"].get(active, "")),
    )


def _localized_category(category: str, lang: str) -> tuple[str, str]:
    active = normalize_language(lang)
    key = category.lower()
    return (
        _SEO_CATEGORY_NAMES[active].get(key, category),
        _SEO_CATEGORY_HINTS[active].get(
            key,
            (
                f"This category groups related SEO checks for {category}."
                if active == "en"
                else f"Категория «{category}» объединяет связанные SEO-проверки."
            ),
        ),
    )

def render_seo_json(report: SeoReport, lang: str | None = None) -> str:
    return json.dumps(report.to_dict(), indent=2, ensure_ascii=False)


def render_seo_jsonl(report: SeoReport, lang: str | None = None) -> str:
    """Emit one bounded summary row per check for streaming-friendly export."""
    rows = [{
        "schema": report.schema,
        "target": report.target,
        "run_id": report.run_id,
        "check_id": item.id,
        "category": item.category,
        "status": item.status,
        "scored": item.scored,
        "priority": next((recommendation.priority for recommendation in report.recommendations if recommendation.check_id == item.id), None),
        "affected_urls": [evidence.url for evidence in item.evidence if evidence.url][:50],
    } for item in report.checks]
    return "".join(json.dumps(row, ensure_ascii=False, sort_keys=True) + "\n" for row in rows)


def render_seo_csv(report: SeoReport, lang: str | None = None) -> str:
    output = io.StringIO()
    fields = ("check_id", "category", "status", "scored", "priority", "affected_urls", "details")
    writer = csv.DictWriter(output, fieldnames=fields)
    writer.writeheader()
    priorities = {item.check_id: item.priority for item in report.recommendations}
    for item in report.checks:
        writer.writerow({
            "check_id": item.id,
            "category": item.category,
            "status": item.status,
            "scored": item.scored,
            "priority": priorities.get(item.id, ""),
            "affected_urls": " ".join(evidence.url for evidence in item.evidence if evidence.url)[:4096],
            "details": item.details,
        })
    return output.getvalue()


def render_seo_console(report: SeoReport, lang: str | None = None) -> str:
    active = normalize_language(lang or report.language)
    labels = _labels(active)
    lines = [f"{labels['title']}: {report.target}", f"{labels['score']}: {report.score}/100", ""]
    if report.inventory:
        lines.append(f"{labels['inventory']}: {json.dumps(report.inventory, ensure_ascii=False, sort_keys=True)}")
    if report.coverage:
        lines.append(f"{labels['coverage']}: {json.dumps(report.coverage, ensure_ascii=False, sort_keys=True)}")
    lines.append(f"{labels['checks']}:")
    for check in report.checks:
        title, category, _ = _localized_check(check.id, check.title, check.category, active)
        lines.append(f"[{labels.get(check.status, check.status)}] {title} ({category}) — {seo_detail(check.details, active)}")
        for item in check.evidence:
            if item.url:
                lines.append(f"  {labels['evidence']} URL: {item.url}")
            if item.metrics:
                lines.append(f"  {labels['evidence']} metrics: {json.dumps(item.metrics, ensure_ascii=False, separators=(',', ':'))}")
    lines.extend(["", f"{labels['categories']}:"])
    lines.extend(
        f"  {_localized_category(item.category, active)[0]}: {item.score if item.score is not None else '-'}"
        for item in report.categories
    )
    if report.recommendations:
        lines.extend(["", f"{labels['recommendations']}:"])
        lines.extend(
            f"  {item.priority}. {_localized_check(item.check_id, item.title, '', active)[0]}: {seo_summary(item.check_id, item.action, active)}"
            for item in report.recommendations
        )
    return "\n".join(lines) + "\n"


def _metric_html(value: object, depth: int = 0) -> str:
    if depth > 3:
        return f"<code>{html.escape(str(value))}</code>"
    if isinstance(value, dict):
        items = "".join(
            f"<li><strong>{html.escape(str(key))}:</strong> {_metric_html(item, depth + 1)}</li>"
            for key, item in value.items()
        )
        return f"<ul>{items}</ul>"
    if isinstance(value, (list, tuple)):
        items = "".join(f"<li>{_metric_html(item, depth + 1)}</li>" for item in value[:100])
        return f"<ul>{items}</ul>"
    return f"<code>{html.escape(str(value))}</code>"


