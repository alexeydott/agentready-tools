def localized_report_dict(report: Any, lang: str | None = None) -> dict[str, Any]:
    """Return a localized JSON-compatible report without mutating core results.

    Machine identifiers (check ``id``, ``status``, preset and numeric scores) stay
    stable. Human-facing titles, descriptions, evidence labels and recommendations
    are localized.
    """
    lang = normalize_language(lang or getattr(report, "language", DEFAULT_LANGUAGE))
    data = asdict(report)
    data["language"] = lang
    data["level_name"] = level_name(report.level, report.level_name, lang)
    if lang == "ru":
        match = re.search(r"sequential (\d+)% tier threshold", report.level_model)
        threshold = match.group(1) if match else "80"
        data["level_model"] = (
            f"прозрачная tier-модель v2; последовательный порог прохождения уровня {threshold}%; "
            "подход вдохновлён открытыми readiness-инструментами; не является неопубликованной формулой Cloudflare"
        )
    for row, src in zip(data.get("checks", []), report.checks):
        row["title"] = check_title(src.id, src.title, lang)
        row["category"] = category_name(src.category, lang)
        row["details"] = detail_text(src.id, src.details, lang)
        for ev, ev_src in zip(row.get("evidence", []), src.evidence):
            ev["action"] = evidence_action(ev_src.action, lang)
            if ev_src.finding:
                ev["finding"] = detail_text(src.id, ev_src.finding, lang)
        if src.remediation and row.get("remediation"):
            row["remediation"]["summary"] = remediation_summary(src.id, src.remediation.summary, lang)
            row["remediation"]["agent_prompt"] = agent_prompt(src.id, report.target, src.remediation.summary, lang)
    for cat, src in zip(data.get("categories", []), report.categories):
        cat["category"] = category_name(src.category, lang)
    if report.next_level and data.get("next_level"):
        data["next_level"]["name"] = level_name(report.next_level.target, report.next_level.name, lang)
        data["next_level"]["requirements"] = [requirement_label(x, lang) for x in report.next_level.requirements]
    for rec, src in zip(data.get("recommendations", []), report.recommendations):
        spec_category = next((c.category for c in report.checks if c.id == src.check_id), "")
        rec["title"] = check_title(src.check_id, src.title, lang)
        rec["action"] = remediation_summary(src.check_id, src.action, lang)
        rec["reason"] = recommendation_reason(spec_category, src.reason, lang)
        rec["impact_label"] = impact_label(src.impact, lang)
        rec["effort_label"] = effort_label(src.effort, lang)
    data["commerce_signals"] = [commerce_signal(x, lang) for x in report.commerce_signals]
    return data
